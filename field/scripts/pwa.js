/**
 * Turns `expo export --platform web` output into an installable web app:
 *   - manifest.webmanifest ("Laboura Field", standalone, theme colour, icons)
 *   - iPhone "Add to Home Screen" tags and the manifest link in index.html
 *   - sw.js, a service worker that caches the app shell so it opens on weak
 *     signal, plus register-sw.js that installs it.
 *
 * Usage: node scripts/pwa.js dist          (base path from app.json: /field/)
 *        node scripts/pwa.js dist-root /    (the build for the root of field.laboura.com)
 *
 * Laboura Field is built twice (decided 14 Nov): `dist` for /field on the
 * office and Render addresses, and `dist-root` for the root of its own
 * address, field.laboura.com. Expo bakes the base path into the bundle, so one
 * build cannot serve both.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const APP = {
  name: 'Laboura Field',
  shortName: 'Laboura Field',
  description: 'Laboura field agent app',
  themeColor: '#0055C0',
  backgroundColor: '#EEF3FC',
};

/** Reads experiments.baseUrl from app.json ("/field") and returns "/field/". */
function basePath(appJsonPath = path.join(__dirname, '..', 'app.json')) {
  const config = JSON.parse(fs.readFileSync(appJsonPath, 'utf8'));
  const base = (config.expo && config.expo.experiments && config.expo.experiments.baseUrl) || '';
  return normaliseBase(base);
}

/** "/field" → "/field/", "" or "/" → "/". */
function normaliseBase(base) {
  const trimmed = String(base || '').replace(/^\/+|\/+$/g, '');
  return trimmed ? `/${trimmed}/` : '/';
}

function buildManifest(base) {
  return {
    id: base,
    name: APP.name,
    short_name: APP.shortName,
    description: APP.description,
    start_url: base,
    scope: base,
    display: 'standalone',
    orientation: 'portrait',
    theme_color: APP.themeColor,
    background_color: APP.backgroundColor,
    lang: 'en',
    icons: [
      { src: `${base}icons/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: `${base}icons/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: `${base}icons/maskable-512.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  };
}

/** Adds the install tags to the exported index.html (idempotent). */
function injectHead(html, base) {
  if (html.includes('data-laboura-pwa')) return html;
  const tags = [
    `<link rel="manifest" href="${base}manifest.webmanifest" data-laboura-pwa>`,
    `<meta name="application-name" content="${APP.name}">`,
    '<meta name="mobile-web-app-capable" content="yes">',
    '<meta name="apple-mobile-web-app-capable" content="yes">',
    `<meta name="apple-mobile-web-app-title" content="${APP.shortName}">`,
    '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">',
    `<link rel="apple-touch-icon" href="${base}icons/apple-touch-icon.png">`,
    '<meta name="format-detection" content="telephone=no">',
    `<script src="${base}register-sw.js" defer></script>`,
  ].join('\n    ');
  let out = html.replace(
    /<meta name="viewport"[^>]*>/,
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />',
  );
  const theme = /<meta name="theme-color"/.test(out) ? '' : `\n    <meta name="theme-color" content="${APP.themeColor}">`;
  out = out.replace('</head>', `    ${tags}${theme}\n  </head>`);
  return out;
}

function listFiles(dir, root = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, root));
    else out.push(path.relative(root, full).split(path.sep).join('/'));
  }
  return out.sort();
}

/** Files the service worker downloads at install: the whole exported app. */
function precacheList(files) {
  return files.filter((f) => !['sw.js', 'metadata.json'].includes(f) && !f.endsWith('.map'));
}

function versionOf(distDir, files) {
  const hash = crypto.createHash('sha256');
  for (const f of files) {
    hash.update(f);
    hash.update(fs.readFileSync(path.join(distDir, f)));
  }
  return hash.digest('hex').slice(0, 12);
}

function buildServiceWorker(base, files, version) {
  const urls = files.map((f) => (f === 'index.html' ? base : base + f));
  return `/* Laboura Field service worker — generated by scripts/pwa.js. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'laboura-field-' + VERSION;
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls, null, 0)};
const NAVIGATION_TIMEOUT_MS = 4000;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

// Keep the newest two versions: a page still open on the previous version can
// load its lazy screens after an update.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then(async (keys) => {
      const ours = keys.filter((k) => k.startsWith('laboura-field-') && k !== CACHE);
      const stale = ours.slice(0, Math.max(0, ours.length - 1));
      await Promise.all(stale.map((k) => caches.delete(k)));
      await self.clients.claim();
    }),
  );
});

const OWN_FILES = new Set(PRECACHE);
const OWN_FOLDERS = [BASE + '_expo/', BASE + 'assets/', BASE + 'icons/'];

// Only the app's own files and its pages. At the root of field.laboura.com the
// scope is "/", the same address as the API (/auth, /attendance…): those calls
// are never answered from the cache.
function isAppRequest(request) {
  if (request.method !== 'GET') return false;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return false;
  const inScope = url.pathname === BASE.slice(0, -1) || url.pathname.startsWith(BASE);
  if (!inScope) return false;
  if (request.mode === 'navigate') return true;
  return OWN_FILES.has(url.pathname) || OWN_FOLDERS.some((folder) => url.pathname.startsWith(folder));
}

// Screens: network first (new deploys show at once), the cached app when the
// signal is too weak to answer within a few seconds.
async function navigation(request) {
  const cache = await caches.open(CACHE);
  const network = fetch(request).then((response) => {
    if (response.ok) cache.put(BASE, response.clone());
    return response;
  });
  const timeout = new Promise((resolve) => setTimeout(resolve, NAVIGATION_TIMEOUT_MS, null));
  try {
    const first = await Promise.race([network, timeout]);
    if (first) return first;
  } catch (e) {
    /* offline */
  }
  const cached = await caches.match(BASE);
  return cached || network;
}

// Files (scripts, fonts, icons): from the cache, else the network.
async function asset(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) (await caches.open(CACHE)).put(request, response.clone());
  return response;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  // API calls (/auth, /attendance…) are never cached: only the app's own files.
  if (!isAppRequest(request)) return;
  const url = new URL(request.url);
  if (url.pathname.endsWith('/sw.js')) return;
  event.respondWith(request.mode === 'navigate' ? navigation(request) : asset(request));
});
`;
}

function buildRegisterScript(base) {
  return `/* Installs the Laboura Field service worker (generated by scripts/pwa.js). */
if ('serviceWorker' in navigator) {
  window.addEventListener('load', function () {
    navigator.serviceWorker.register(${JSON.stringify(base + 'sw.js')}, { scope: ${JSON.stringify(base)} }).catch(function () {});
  });
}
`;
}

function run(distDir, base = basePath()) {
  base = normaliseBase(base);
  const indexPath = path.join(distDir, 'index.html');
  if (!fs.existsSync(indexPath)) throw new Error(`${indexPath} not found — run expo export first`);
  fs.writeFileSync(indexPath, injectHead(fs.readFileSync(indexPath, 'utf8'), base));
  fs.writeFileSync(path.join(distDir, 'manifest.webmanifest'), `${JSON.stringify(buildManifest(base), null, 2)}\n`);
  fs.writeFileSync(path.join(distDir, 'register-sw.js'), buildRegisterScript(base));
  const files = precacheList(listFiles(distDir));
  const version = versionOf(distDir, files);
  fs.writeFileSync(path.join(distDir, 'sw.js'), buildServiceWorker(base, files, version));
  return { files, version };
}

if (require.main === module) {
  const dir = path.resolve(process.argv[2] || 'dist');
  const base = process.argv[3] === undefined ? basePath() : normaliseBase(process.argv[3]);
  const { files, version } = run(dir, base);
  console.log(`Laboura Field web app (${base}) ready in ${dir}: ${files.length} files cached by sw.js (version ${version}).`);
}

module.exports = { basePath, normaliseBase, buildManifest, injectHead, buildServiceWorker, buildRegisterScript, precacheList, listFiles, run };
