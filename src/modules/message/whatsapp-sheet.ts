import {
  WHATSAPP_TEMPLATES,
  WhatsAppTemplateDef,
  metaParameterName,
  sampleValue,
} from './whatsapp-templates';

/** Where the submission sheet lives (generated, never edited by hand). */
export const WHATSAPP_SHEET_PATH = 'docs/whatsapp-templates.md';

/** The body as Meta wants it: `{{first_name}}` instead of `{{firstName}}`. */
export function metaBody(def: WhatsAppTemplateDef): string {
  return def.text.replace(/\{\{(\w+)\}\}/g, (_, key: string) => `{{${metaParameterName(key)}}}`);
}

function cell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

/**
 * The copy-paste sheet for WhatsApp Manager (Master Guide rev 211): one block per
 * template with its name, category, language, body with lowercase_underscore
 * variables, a sample value for every variable and notes. Built only from
 * whatsapp-templates.ts, so `npm run whatsapp:sheet` and the test agree.
 */
export function renderWhatsAppSheet(): string {
  const defs = Object.values(WHATSAPP_TEMPLATES as Record<string, WhatsAppTemplateDef>);
  const lines: string[] = [
    '# WhatsApp templates: submission sheet',
    '',
    '<!-- Generated by `npm run whatsapp:sheet` from src/modules/message/whatsapp-templates.ts. Do not edit by hand: change the template file and run the script again (a test fails while this sheet is out of date). -->',
    '',
    'Submit each template below in WhatsApp Manager (Message templates → Create template) with exactly this name, category, language and body. Variables are named parameters ("Name" type, lowercase with underscores). Enter the sample values Meta asks for. Every name must be approved before `WHATSAPP_PROVIDER_MODE=meta` can send it; until then the SMS backup carries the message.',
    '',
    `Templates: ${defs.length}.`,
    '',
    '| Name | Category | Language | Variables |',
    '| --- | --- | --- | --- |',
    ...defs.map((d) => `| \`${d.name}\` | ${categoryLabel(d)} | en | ${d.variables.length} |`),
    '',
  ];
  for (const def of defs) {
    lines.push(`## ${def.name}`, '');
    lines.push(`- **Name:** \`${def.name}\``);
    lines.push(`- **Category:** ${categoryLabel(def)}`);
    lines.push('- **Language:** English (`en`)');
    lines.push(`- **What it is for:** ${def.label}`);
    if (def.notes) lines.push(`- **Notes:** ${def.notes}`);
    lines.push('', '**Body**', '', '```text', metaBody(def), '```', '');
    if (def.variables.length) {
      lines.push('| Variable | Sample value |', '| --- | --- |');
      for (const key of def.variables) lines.push(`| \`{{${metaParameterName(key)}}}\` | ${cell(sampleValue(def, key))} |`);
    } else {
      lines.push('No variables.');
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function categoryLabel(def: WhatsAppTemplateDef): string {
  return def.category === 'authentication' ? 'Authentication' : 'Utility';
}
